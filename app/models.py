from pydantic import BaseModel, Field
from typing import List, Optional, Any

class QueryRequest(BaseModel):
    question: str

class RAGResponse(BaseModel):
    # Field definitions with type hints
    answer: str = Field(description="The primary answer generated by the AI.")
    confidence: float = Field(ge=0.0, le=1.0, description="Confidence score between 0 and 1.")
    is_complete: bool = Field(description="Whether the answer fully satisfies the query.")
    missing_info: Optional[str] = Field(None, description="Details on what information is lacking.")
    enrichment_suggestions: List[str] = Field(default_factory=list, description="Suggestions to improve the knowledge base.")